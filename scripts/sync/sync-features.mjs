#!/usr/bin/env node

/**
 * 编译期特性自动发现与注册表生成脚本 (Feature Auto-Discovery & Registry Sync)
 * 遵循 ADR-006：将注册表生成在应用装配层 apps/tenant/src/kernel/registry.generated.ts，
 * 彻底解除业务切片之间的反向依赖与循环依赖。
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function findWorkspaceRoot(startDir = __dirname) {
  let curr = path.resolve(startDir);
  while (curr !== path.dirname(curr)) {
    if (fs.existsSync(path.join(curr, "pnpm-workspace.yaml"))) {
      return curr;
    }
    curr = path.dirname(curr);
  }
  return path.resolve(startDir, "../..");
}

const rootDir = findWorkspaceRoot(__dirname);
const domainsDir = path.resolve(rootDir, "packages/domains");
const platformTenantAdminDir = path.resolve(
  rootDir,
  "packages/platform/tenant-admin",
);
const targetDir = path.resolve(rootDir, "packages/runtime/tenant/src");
const targetFile = path.resolve(targetDir, "registry.ts");

function discoverFeatureManifests() {
  const discovered = [];

  // 1. 发现租户平台基座套件 (tenant-admin)
  if (fs.existsSync(platformTenantAdminDir)) {
    const manifestPath = path.resolve(
      platformTenantAdminDir,
      "src/manifest.ts",
    );
    const pkgJsonPath = path.resolve(platformTenantAdminDir, "package.json");
    if (fs.existsSync(manifestPath) && fs.existsSync(pkgJsonPath)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf-8"));
        const manifestCode = fs.readFileSync(manifestPath, "utf-8");
        const match = manifestCode.match(/export\s+const\s+(\w+Manifest)\s*:/);
        if (match) {
          const manifestSubpath = pkg.exports?.["./manifest"]
            ? `${pkg.name}/manifest`
            : pkg.name;
          discovered.push({
            dirName: "tenant-admin",
            packageName: manifestSubpath,
            exportName: match[1],
            isTenantAdmin: true,
          });
        }
      } catch (err) {
        console.warn("[sync-features] 跳过解析 tenant-admin:", err.message);
      }
    }
  }

  // 2. 纯粹发现业务领域切片 (packages/domains/*)
  if (fs.existsSync(domainsDir)) {
    const entries = fs.readdirSync(domainsDir, { withFileTypes: true });
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;

      const manifestPath = path.resolve(
        domainsDir,
        entry.name,
        "src/manifest.ts",
      );
      const pkgJsonPath = path.resolve(domainsDir, entry.name, "package.json");

      if (fs.existsSync(manifestPath) && fs.existsSync(pkgJsonPath)) {
        try {
          const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf-8"));
          const manifestCode = fs.readFileSync(manifestPath, "utf-8");

          const match = manifestCode.match(
            /export\s+const\s+(\w+Manifest)\s*:/,
          );
          if (match) {
            const manifestSubpath = pkg.exports?.["./manifest"]
              ? `${pkg.name}/manifest`
              : pkg.name;
            discovered.push({
              dirName: entry.name,
              packageName: manifestSubpath,
              exportName: match[1],
              isTenantAdmin: false,
            });
          }
        } catch (err) {
          console.warn(`[sync-features] 跳过解析 ${entry.name}:`, err.message);
        }
      }
    }
  }

  // 保证排序稳定，tenant-admin 放在首位作为系统支撑模块
  discovered.sort((a, b) => {
    if (a.isTenantAdmin) return -1;
    if (b.isTenantAdmin) return 1;
    return a.dirName.localeCompare(b.dirName);
  });

  return discovered;
}

function generateRegistryCode(features) {
  const imports = [
    'import type { TenantFeatureManifest, StandardPageDescriptor } from "@base/authorization";',
    "import {",
    "  deriveCatalogDefinitions,",
    "  derivePermissionCatalog,",
    "  derivePermissionTree,",
    "  derivePageList,",
    "  derivePageCatalog,",
    '} from "@base/authorization";',
  ];

  for (const f of features) {
    imports.push(`import { ${f.exportName} } from "${f.packageName}";`);
  }

  const manifestList = features.map((f) => `  ${f.exportName},`).join("\n");
  const businessFeatures = features.filter((f) => !f.isTenantAdmin);
  const businessManifestList = businessFeatures
    .map((f) => `  ${f.exportName},`)
    .join("\n");

  return `// @generated by scripts/sync-features.mjs - DO NOT EDIT MANUALLY
/**
 * 全局租户自描述特性注册表（编译期自动发现生成）
 * 遵循 ADR-006：集中在应用内核装配层，消除切片间横向依赖。
 */
${imports.join("\n")}

export const ALL_TENANT_MANIFESTS = [
${manifestList}
] as const;

/**
 * 自动从全局聚合清单中推导所有切片受控实体的全局 Subject 联合类型 (SSoT)
 * 新增任何业务切片时由编译期自动发现生成，内核无需手工维护枚举
 */
export type GlobalTenantSubject = NonNullable<
  typeof ALL_TENANT_MANIFESTS[number]["permissionModules"]
>[number]["pages"][number]["subject"];

/** 纯业务切片清单 (排除系统管理，供业务自定义菜单选用) */
export const BUSINESS_TENANT_MANIFESTS: readonly TenantFeatureManifest[] = [
${businessManifestList}
] as const;

/** 全局租户权限清单定义数组 (无伪模块，纯业务实体) */
export const globalTenantCatalogDefinitions = deriveCatalogDefinitions(
  ALL_TENANT_MANIFESTS,
);

/** 全局租户 CASL PermissionCatalog 实例 (供全局 Ability 工厂编译使用) */
export const globalTenantCatalog = derivePermissionCatalog(ALL_TENANT_MANIFESTS);

/** 全局租户角色权限管理树 (供系统管理 / 角色权限配置界面直接消费) */
export const globalTenantPermissionTree = derivePermissionTree(ALL_TENANT_MANIFESTS);

/** 全局租户可用标准功能页面池清单 (纯数据数组，全量页面) */
export const globalTenantPageList: readonly StandardPageDescriptor[] = derivePageList(
  ALL_TENANT_MANIFESTS,
);

/** 纯业务功能页面池清单 (排除工作台与系统管理，专供租户业务菜单配置选用) */
export const globalBusinessPageList: readonly StandardPageDescriptor[] = derivePageList(
  BUSINESS_TENANT_MANIFESTS,
);

/** 全局租户可用标准功能页面池 Map 索引 (供服务端运行时高频快速定位权限与路由) */
export const globalTenantPageCatalog: ReadonlyMap<string, StandardPageDescriptor> = derivePageCatalog(
  ALL_TENANT_MANIFESTS,
);
`;
}

function main() {
  const features = discoverFeatureManifests();
  const code = generateRegistryCode(features);

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  if (fs.existsSync(targetFile)) {
    const existing = fs.readFileSync(targetFile, "utf-8");
    if (existing === code) {
      console.log("✓ [sync-features] 特性注册表已是最新，跳过写入。");
      return;
    }
  }

  fs.writeFileSync(targetFile, code, "utf-8");
  console.log(
    `✓ [sync-features] 成功自动发现 ${features.length} 个租户切片并生成静态注册表 -> ${path.relative(rootDir, targetFile)}`,
  );
}

main();
