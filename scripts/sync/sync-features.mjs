#!/usr/bin/env node

/**
 * 编译期特性自动发现与注册表生成脚本 (Feature Auto-Discovery & Registry Sync)
 * 遵循 ADR-006：将注册表生成在应用装配层 apps/tenant/src/kernel/registry.generated.ts，
 * 彻底解除业务切片之间的反向依赖与循环依赖。
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function findWorkspaceRoot(startDir = __dirname) {
  let curr = path.resolve(startDir);
  while (curr !== path.dirname(curr)) {
    if (fs.existsSync(path.join(curr, "pnpm-workspace.yaml"))) {
      return curr;
    }
    curr = path.dirname(curr);
  }
  return path.resolve(startDir, "../..");
}

const rootDir = findWorkspaceRoot(__dirname);
const featuresDir = path.resolve(rootDir, "packages/features");
const targetDir = path.resolve(rootDir, "apps/tenant/src/kernel");
const targetFile = path.resolve(targetDir, "registry.generated.ts");

function discoverFeatureManifests() {
  if (!fs.existsSync(featuresDir)) {
    return [];
  }

  const entries = fs.readdirSync(featuresDir, { withFileTypes: true });
  const discovered = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    // 跳过平台总控切片 (control-admin)，仅聚合租户端业务切片
    if (entry.name === "control-admin") continue;

    const manifestPath = path.resolve(
      featuresDir,
      entry.name,
      "src/manifest.ts",
    );
    const pkgJsonPath = path.resolve(featuresDir, entry.name, "package.json");

    if (fs.existsSync(manifestPath) && fs.existsSync(pkgJsonPath)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, "utf-8"));
        const manifestCode = fs.readFileSync(manifestPath, "utf-8");

        // 匹配 export const xxxManifest；优先使用显式 manifest subpath。
        const match = manifestCode.match(/export\s+const\s+(\w+Manifest)\s*:/);
        if (match) {
          const manifestSubpath = pkg.exports?.["./manifest"]
            ? `${pkg.name}/manifest`
            : pkg.name;
          discovered.push({
            dirName: entry.name,
            packageName: manifestSubpath,
            exportName: match[1],
            isTenantAdmin: entry.name === "tenant-admin",
          });
        }
      } catch (err) {
        console.warn(`[sync-features] 跳过解析 ${entry.name}:`, err.message);
      }
    }
  }

  // 保证排序稳定，tenant-admin 放在首位作为系统支撑模块
  discovered.sort((a, b) => {
    if (a.isTenantAdmin) return -1;
    if (b.isTenantAdmin) return 1;
    return a.dirName.localeCompare(b.dirName);
  });

  return discovered;
}

function generateRegistryCode(features) {
  const imports = [
    'import type { TenantFeatureManifest } from "@base/authorization";',
    "import {",
    "  deriveCatalogDefinitions,",
    "  derivePermissionCatalog,",
    "  deriveNavSections,",
    "  derivePermissionTree,",
    '} from "@base/authorization";',
  ];

  for (const f of features) {
    imports.push(`import { ${f.exportName} } from "${f.packageName}";`);
  }

  const manifestList = features.map((f) => `  ${f.exportName},`).join("\n");

  return `// @generated by scripts/sync-features.mjs - DO NOT EDIT MANUALLY
/**
 * 全局租户自描述特性注册表（编译期自动发现生成）
 * 遵循 ADR-006：集中在应用内核装配层，消除切片间横向依赖。
 */
${imports.join("\n")}

export const ALL_TENANT_MANIFESTS: readonly TenantFeatureManifest[] = [
${manifestList}
] as const;

/** 全局租户权限清单定义数组 (无伪模块，纯业务实体) */
export const globalTenantCatalogDefinitions = deriveCatalogDefinitions(
  ALL_TENANT_MANIFESTS,
);

/** 全局租户 CASL PermissionCatalog 实例 (供全局 Ability 工厂编译使用) */
export const globalTenantCatalog = derivePermissionCatalog(ALL_TENANT_MANIFESTS);

/** 全局租户侧边栏导航区块定义 (含工作台、客户中心、业务中心、系统管理) */
export const globalTenantNavSections = deriveNavSections(ALL_TENANT_MANIFESTS);

/** 全局租户角色权限管理树 (供系统管理 / 角色权限配置界面直接消费) */
export const globalTenantPermissionTree = derivePermissionTree(ALL_TENANT_MANIFESTS);
`;
}

function main() {
  const features = discoverFeatureManifests();
  const code = generateRegistryCode(features);

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  if (fs.existsSync(targetFile)) {
    const existing = fs.readFileSync(targetFile, "utf-8");
    if (existing === code) {
      console.log("✓ [sync-features] 特性注册表已是最新，跳过写入。");
      return;
    }
  }

  fs.writeFileSync(targetFile, code, "utf-8");
  console.log(
    `✓ [sync-features] 成功自动发现 ${features.length} 个租户切片并生成静态注册表 -> ${path.relative(rootDir, targetFile)}`,
  );
}

main();
